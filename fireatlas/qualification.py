"""Hash-bound research protocols and human-owned approval gates.

Templates are deliberately unsigned. Engineering or synthetic test success never
creates independent scientific approval. Existing v1 releases are not modified.
"""
from __future__ import annotations
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROTOCOLS = Path(__file__).with_name('protocols')


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':'), allow_nan=False).encode()).hexdigest()


def protocol(kind='monthly'):
    if kind not in ('monthly', 'daily'):
        raise ValueError('Unknown research protocol.')
    value = json.loads((PROTOCOLS / f"{kind}-{'v2.0.5' if kind == 'daily' else 'v2.0.4'}.json").read_text())
    for relative,expected in value.get('method_annex',{}).get('source_sha256',{}).items():
        path=ROOT/relative
        if not path.resolve().is_relative_to(ROOT) or hashlib.sha256(path.read_bytes()).hexdigest()!=expected:
            raise ValueError('Frozen method source differs; create a new protocol version and obtain renewed review before evaluation.')
    return {**value, 'protocol_sha256': digest(value)}


def review_template(kind='monthly'):
    p = protocol(kind)
    return {'schema': 'fireatlas-method-review-v1', 'protocol_id': p['id'],
            'protocol_sha256': p['protocol_sha256'], 'decision': 'pending',
            'reviewer': {'name': '', 'affiliation': '', 'qualification': '', 'independence_statement': ''},
            'signed_utc': None, 'human_authored': False, 'automated_agent': None,
            'scope': 'protocol', 'comments': '', 'evidence_sha256': None}


def approval(review, kind='monthly', *, scope='protocol', evidence_sha256=None):
    """Validate an imported human attestation, not the identity of its author.

The owner must verify the signed reviewer document outside the software. No
boolean generated by a model substitutes for that signed, hash-bound document.
"""
    p = protocol(kind)
    if not isinstance(review, dict):
        return {'approved': False, 'reason': 'human-review-missing'}
    reviewer = review.get('reviewer')
    if not isinstance(reviewer, dict):
        return {'approved': False, 'reason': 'malformed-reviewer'}
    checks = [review.get('schema') == 'fireatlas-method-review-v1',
              review.get('protocol_id') == p['id'], review.get('protocol_sha256') == p['protocol_sha256'],
              review.get('decision') == 'approve', review.get('scope') == scope,
              review.get('human_authored') is True, review.get('automated_agent') is False,
              review.get('evidence_sha256') == evidence_sha256,
              all(isinstance(reviewer.get(k), str) and bool(reviewer[k].strip())
                  for k in ('name', 'affiliation', 'qualification', 'independence_statement'))]
    try:
        stamp = datetime.fromisoformat(review.get('signed_utc', '').replace('Z', '+00:00'))
        checks.append(stamp.tzinfo is not None and stamp.utcoffset().total_seconds() == 0 and stamp <= datetime.now(timezone.utc))
    except (ValueError, TypeError, AttributeError):
        checks.append(False)
    return {'approved': all(checks), 'reason': 'owner-verified-human-attestation-required' if not all(checks) else 'imported-human-attestation',
            'review_sha256': digest(review), 'protocol_sha256': p['protocol_sha256']}


def require_approval(review, kind='monthly'):
    state = approval(review, kind)
    if not state['approved']:
        raise ValueError('Evaluation withheld: a signed independent protocol approval is required before inspecting new results.')
    return state


def experimental_review(kind='monthly'):
    """AI audit provenance for user-authorized exploration, never human approval.

    This receipt is a reproducible declaration, not authentication of a person
    or a replacement for any scientific release gate.
    """
    p = protocol(kind)
    policy = json.loads((PROTOCOLS / 'ai-exploration-v2.json').read_text())
    if policy['protocol_ids'].get(kind) != p['id']:
        raise ValueError('Experimental policy does not cover this protocol version.')
    for relative, expected in policy['audit_sha256'].items():
        path = ROOT / relative
        if not path.resolve().is_relative_to(ROOT) or hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            raise ValueError('AI audit bytes differ from the frozen experimental policy.')
    return {'schema':'fireatlas-ai-experimental-review-v1', 'policy':policy,
            'policy_sha256':digest(policy), 'protocol_id':p['id'],
            'protocol_sha256':p['protocol_sha256'], 'human_authored':False,
            'automated_agent':True, 'independent_scientific_approval':False}


def require_evaluation_review(review, kind='monthly', *, experimental=None, synthetic=False):
    if experimental is not None:
        if synthetic or review is not None:
            raise ValueError('Experimental AI review cannot mix with synthetic mode or human review.')
        if not isinstance(experimental, dict) or digest(experimental) != digest(experimental_review(kind)):
            raise ValueError('Experimental review does not match the frozen AI audit and protocol.')
        return
    if not synthetic:
        require_approval(review, kind)
